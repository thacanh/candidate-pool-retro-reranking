"""Generate final-round manuscript tables from frozen outputs; never run experiments."""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "outputs/dd_final_round"
PAPER = ROOT / "paper/digital_discovery"
POOLS = {"historical_cap10": "Historical", "aizynthfinder_only": "Anchored AiZ",
         "localretro_only": "LocalRetro", "merged": "Merged"}


def read_csv(name):
    with (DATA / name).open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def read_json(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def pp(value):
    return f"${100 * float(value):+.3f}$"


def interval(row, prefix):
    return f"[{pp(row[prefix + '_ci95_low'])}, {pp(row[prefix + '_ci95_high'])}]"


def table(caption, label, columns, header, rows):
    return "\n".join([
        r"\begin{table*}[t]", r"\small", r"\caption{" + caption + "}",
        r"\label{" + label + "}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}" + columns + "}",
        r"\hline", " & ".join(header) + r" \\", r"\hline",
        *[" & ".join(row) + r" \\" for row in rows],
        r"\hline", r"\end{tabular*}", r"\end{table*}", "",
    ])


def main():
    n2 = read_csv("N2/cross_inference_effects.csv")
    n3 = read_csv("N3_S3/transfer_effects.csv")
    n4 = read_csv("N4/transfer_effects.csv")
    choices = read_json("N3_S2/choice_freeze.json")
    assert choices["test_partition_loaded"] is False
    assert len(n2) == 8 and len(n3) == len(n4) == 6
    counts = {}
    for name, rows in (("N3", n3), ("N4", n4)):
        assert len({(r["pool"], r["metric"]) for r in rows}) == 6
        for r in rows:
            assert int(r["common_reactions"]) == 3814
            assert abs(float(r["expanded_effect"]) - float(r["historical_effect"])
                       - float(r["transfer_loss"])) < 1e-12
        counts[name] = sum(float(r["crossed_ci95_high"]) < 0 for r in rows)
    assert counts == {"N3": 3, "N4": 1}
    clipping = max(float(r["prior_total_clipped_fraction"])
                   for r in read_csv("N2/clipping.csv"))
    assert clipping == 0
    metrics = {"top1": "Top-1", "mrr": "MRR"}
    parts = [r"% Generated by scripts/summarize_dd_final_round.py; values are percentage points."]
    parts.append(table(
        "N2 fixed-checkpoint cross-inference on 3,814 common reactions, seeds 42--61. "
        "Effects are Uni-Mol augmented minus prior-plus-2D baseline, in percentage points. "
        "Off-diagonal cells are descriptive because prior semantics differ between pools; "
        "positive increments are not absolute model accuracies or proof of deployment transfer.",
        "tab:n2_cross", "lllrrr",
        ["Train pool", "Evaluate pool", "Endpoint", "Effect", "Product 95\\% CI", "Crossed 95\\% CI"],
        [[POOLS[r["training_pool"]], POOLS[r["evaluation_pool"]], metrics[r["metric"]],
          pp(r["effect"]), interval(r, "product"), interval(r, "crossed")] for r in n2]))
    parts.append(table(
        "N3 baseline validation-MRR selection over seeds 42--46 (absolute proportions). "
        "One transform per pool was frozen for both arms before the new test evaluation. "
        "These small selection gains do not constitute a full hyperparameter search.",
        "tab:n3_selection", "lrrrrl",
        ["Pool", "Raw", "Log", "Rank", "Gain over raw", "Selected"],
        [[POOLS[p], *[f"{c['validation'][t]['mean_best_validation_mrr']:.9f}" for t in ("raw", "log", "rank")],
          f"{c['validation'][c['selected']]['mean_best_validation_mrr'] - c['validation']['raw']['mean_best_validation_mrr']:.9f}",
          c["selected"]] for p, c in choices["choices"].items()]))
    for name, rows, encoder in (("n3", n3, "Uni-Mol after validation-only prior re-selection"),
                               ("n4", n4, "Morgan-atom features with frozen ranking settings")):
        parts.append(table(
            f"{name.upper()} {encoder}: common-cohort effects and direct transfer loss "
            "(expanded minus historical effect), all in percentage points. All cells use "
            "3,814 reactions and 20 paired seeds. Product-only and crossed product--seed "
            "intervals are both reported; intervals are pointwise, not multiplicity-adjusted.",
            f"tab:{name}_transfer", "llrrrrr",
            ["Pool", "Endpoint", "Historical", "Expanded", "Loss", "Product 95\\% CI", "Crossed 95\\% CI"],
            [[POOLS[r["pool"]], metrics[r["metric"]], pp(r["historical_effect"]), pp(r["expanded_effect"]),
              pp(r["transfer_loss"]), interval(r, "product"), interval(r, "crossed")] for r in rows]))
    sources = ["N2/cross_inference_effects.csv", "N2/clipping.csv", "N3_S2/choice_freeze.json",
               "N3_S3/transfer_effects.csv", "N4/transfer_effects.csv",
               "N4/replay_audit/n4_reproduction_audit_approved.jsonl",
               "N3_return_audit_20260923/manifest.json", "N4_return_audit_20260924/manifest.json"]
    local = ROOT / "outputs/digital_discovery_final_round"
    n1_path = local / "n1_matched_list_joint_sensitivity_v2/n1_joint_pipeline_contrasts.csv"
    n5_path = local / "n5_crossed_transfer/n5_crossed_transfer_intervals.csv"
    with n1_path.open(encoding="utf-8", newline="") as handle:
        n1 = list(csv.DictReader(handle))
    with n5_path.open(encoding="utf-8", newline="") as handle:
        n5 = list(csv.DictReader(handle))
    assert len(n1) == 4 and len(n5) == 6
    assert all(float(r["crossed_product_seed_ci95_high"]) < 0 for r in n5)
    hashes = {p: hashlib.sha256((DATA / p).read_bytes()).hexdigest() for p in sources}
    for p in (n1_path, n5_path):
        relative = "../digital_discovery_final_round/" + p.relative_to(local).as_posix()
        hashes[relative] = hashlib.sha256(p.read_bytes()).hexdigest()
    parts.append(table(
        "Final-round artifact ledger. Paths are relative to outputs/dd\\_final\\_round/. "
        "Hashes identify frozen numerical inputs and the local import audits; no scientific output is rewritten.",
        "tab:final_hash", "p{8.0cm}p{8.3cm}", ["Artifact", "SHA256 (two consecutive halves)"],
        [[r"\path{" + p + "}", r"\texttt{" + h[:32] + r"}\newline\texttt{" + h[32:] + "}"]
         for p, h in hashes.items()]))
    parts.append(table(
        "N1 secondary matched-list joint-pipeline sensitivity. Effects are differences of "
        "augmented-minus-baseline increments between AiZynthFinder and historical pipelines, "
        "in percentage points. Candidate-identity/order matches are not exact-feature matches: "
        "stored prior values differ for every reaction. Sign-flip p values are unadjusted.",
        "tab:n1_joint", "llrrrrr",
        ["Cohort", "Endpoint", "Reactions", "Difference", "Product 95\\% CI", "Crossed 95\\% CI", "$p$"],
        [["Matched lists" if r["cohort"].startswith("matched") else "Changed lists", metrics[r["metric"]],
          r["n_reactions"], pp(r["aizynth_minus_historical_increment"]), interval(r, "product_cluster"),
          interval(r, "crossed_product_seed"), f"{float(r['product_cluster_sign_flip_p']):.5f}"] for r in n1]))
    parts.append(table(
        "N5 crossed product--seed uncertainty for the unchanged primary M2b transfer effects "
        "on 3,814 common reactions, seeds 42--61. Values are percentage points. These "
        "pointwise intervals supplement, rather than replace, the original product-cluster "
        "intervals and Holm-adjusted primary tests.",
        "tab:n5_crossed", "llrr", ["Pool", "Endpoint", "Transfer loss", "Crossed 95\\% CI"],
        [[POOLS[r["pool"]], metrics[r["metric"]], pp(r["mean_transfer_loss"]),
          interval(r, "crossed_product_seed")] for r in n5]))
    target = PAPER / "tables/final_round_n2_n4.tex"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(parts), encoding="utf-8")
    report = {
        "status": "complete", "operation": "reporting-only; no scientific experiment",
        "common_reactions": 3814, "seeds": list(range(42, 62)),
        "n2_prior_clipping_maximum": clipping, "crossed_negative_transfer_intervals": counts,
        "n1": n1, "n2": n2, "n3": n3, "n4": n4, "n5": n5, "source_sha256": hashes,
        "ci_recomputed": False,
        "caveats": ["N2 off-diagonal effects are descriptive despite zero prior clipping.",
                    "N3 is prior-transform re-selection, not the unrun 81-configuration extension.",
                    "N4 retains approved frozen first-five predictions despite seven replay rank differences.",
                    "Transfer-loss CIs must not be interpreted as own-pool effect CIs.",
                    "Pointwise CIs in these sensitivity families are not adjusted for multiplicity."],
    }
    out = DATA / "reporting_20260924"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": "complete", "tables": 7, "crossed_negative_intervals": counts,
                      "n2_maximum_prior_clipping": clipping}))


if __name__ == "__main__":
    main()
